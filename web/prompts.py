def build_prompt(slug: str, user_extra: str | None = None) -> str:
    """slug 에 해당하는 최종 프롬프트를 만든다.

    slug       : hairstyles.slug (regent, hush, ...)
    user_extra : 2단계 사용자 자유 입력. None 이면 추천 스타일 그대로.
    """
    if slug not in STYLE_PROMPTS:
        raise KeyError(f"등록되지 않은 스타일 slug: {slug}")

    prompt = BASE + STYLE_PROMPTS[slug]

    if user_extra:
        cleaned = user_extra.strip()[:200]        # 길이 제한으로 남용 억제
        if cleaned:
            prompt += USER_EXTRA_WRAPPER.format(user_extra=cleaned)

    return prompt


def check_against_db_slugs(db_slugs) -> None:
    """DB 의 slug 목록과 대조. 누락/잉여가 있으면 예외를 던진다.

    db_setup_v2.HAIRSTYLES 를 바꿨는데 여기를 안 고치는 사고를 막는다.
    """
    db = set(db_slugs)
    mine = set(STYLE_PROMPTS)
    missing, extra = db - mine, mine - db
    if missing or extra:
        raise ValueError(
            f"프롬프트 불일치 — DB 에만 있음: {sorted(missing)} / "
            f"프롬프트에만 있음: {sorted(extra)}"
        )


